    /**
     * @param  array<string, string>  $entries
     * @return array<int, array<string, mixed>>
     */
    private function entriesFrom(string $group, array $entries): array
    {
        return collect($entries)
            ->map(fn (string $value, string $key): array => $this->entry($group, $key, $this->sameValue($value)))
            ->values()
            ->all();
    }

    /**
     * @return array<string, string>
     */
    private function sameValue(string $value): array
    {
        return [
            'ru' => $value,
            'en' => $value,
            'lt' => $value,
            'pl' => $value,
        ];
    }
